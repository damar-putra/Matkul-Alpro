# Program Menampilkan Deret Angka
print("=== PROGRAM DERET ANGKA ===")

# Deret angka 1 sampai 10
print("Deret Asli (1-10):")
for i in range(1, 11):
    print(i, end=" ")

# Deret Genap (2 sampai 20, lompat 2)
print("\n\nDeret Genap (2-20):")
for j in range(2, 21, 2):
    print(j, end=" ")

# Deret Mundur (10 sampai 1)
print("\n\nDeret Mundur (10-1):")
for k in range(10, 0, -1):
    print(k, end=" ")
